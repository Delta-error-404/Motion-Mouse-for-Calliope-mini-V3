// ============================================================
// Motion Mouse - Calliope mini V3
// USB Version
// ============================================================

// ------------------------------------------------------------
// Button states
// ------------------------------------------------------------

let aPressed = false
let bPressed = false

let lastA = false
let lastB = false

// ------------------------------------------------------------
// Accelerometer values
// ------------------------------------------------------------

let x = 0
let y = 0

// ------------------------------------------------------------
// Startup
// ------------------------------------------------------------

// Small startup animation
basic.showIcon(IconNames.Yes)
basic.pause(500)
basic.clearScreen()

// ------------------------------------------------------------
// Main mouse loop
// ------------------------------------------------------------

basic.forever(function () {

    // ========================================================
    // Read accelerometer
    // ========================================================

    x = input.acceleration(Dimension.X)
    y = input.acceleration(Dimension.Y)

    // ========================================================
    // Read buttons
    // ========================================================

    aPressed = input.buttonIsPressed(Button.A)
    bPressed = input.buttonIsPressed(Button.B)

    // ========================================================
    // A + B = scroll mode
    // ========================================================

    if (aPressed && bPressed) {

        serial.writeLine(
            "SCROLL," + y
        )

    } else {

        // ====================================================
        // Normal mouse movement
        // ====================================================

        serial.writeLine(
            "MOVE," + x + "," + y
        )
    }

    // ========================================================
    // Button A = left click
    // ========================================================

    if (aPressed && !lastA && !bPressed) {

        serial.writeLine(
            "CLICK_L"
        )
    }

    // ========================================================
    // Button B = right click
    // ========================================================

    if (bPressed && !lastB && !aPressed) {

        serial.writeLine(
            "CLICK_R"
        )
    }

    // ========================================================
    // Remember button states
    // ========================================================

    lastA = aPressed
    lastB = bPressed

    // ========================================================
    // Update rate: 100 Hz
    // ========================================================

    basic.pause(10)
})
